// Pruebas deterministas: node js/cards/card-system.test.js
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.join(__dirname, '../..');
const G = { Acquisition: { gacha: { rates: [[1,65],[2,23],[3,9],[4,2.5],[5,.5]], duplicateRefund: {1:15,2:30,3:60,4:120,5:300} } }, UI: { $() {} } };
global.G = G;
vm.runInThisContext(fs.readFileSync(path.join(root, 'js/data/pokedex.js'), 'utf8'));
G.DB = { save: { coins: 3000, tickets: { t1: 30 }, owned: {}, cardCollection: {v:1,fragments:{},discovered:{},operations:{}} }, commit() {}, recordPokemon() {} };
G.UI = { $() {}, refreshCoins() {} };
global.G = G;
vm.runInThisContext(fs.readFileSync(path.join(__dirname, 'card-system.js'), 'utf8'));
assert.equal(G.CardSystem.validate(), true);
assert.deepEqual([0,.65,.88,.97,.995].map(x=>G.CardSystem.selectRarity(()=>x)), [1,2,3,4,5]);
assert.deepEqual(Object.values(G.CardSystem.CONFIG.fragmentsRequiredByRarity), [3,4,5,3,2]);
assert.equal(G.CardSystem.probabilityRows().reduce((n,r)=>n+r.weight,0), 100);
assert.equal(G.CardSystem.probabilityRows().reduce((n,r)=>n+r.actualWeight,0), 100);
assert.equal(G.CardSystem.unmatched.length, 0, `Sin asociación: ${G.CardSystem.unmatched.map(c=>c.sourceName).join(', ')}`);
for (const card of G.CardSystem.catalog) assert.ok(fs.existsSync(path.join(root, card.image)), `Falta imagen ${card.image}`);
for (const pack of G.CardSystem.CONFIG.pack.variants) assert.ok(fs.existsSync(path.join(root, pack.image)), `Falta sobre ${pack.image}`);
const before = G.DB.save.coins; G.DB.save.coins = 299;
assert.throws(() => G.CardSystem.open({rng:()=>0}), /300 monedas y 3 tickets/);
assert.equal(G.DB.save.coins, 299);
G.DB.save.coins = 3000; G.DB.save.tickets.t1 = 30;
const missing = G.CardSystem.probabilityRows().find(r => r.cardCount === 0);
if (missing) {
  const prefix = G.CardSystem.CONFIG.rarityRates.filter(r=>r.rarity<missing.rarity).reduce((n,r)=>n+r.weight,0);
  let call = 0; const fallback = G.CardSystem.open({rng:()=>call++ ? 0 : (prefix + .01) / 100, operationId:'fallback'});
  assert.notEqual(fallback.rarity, missing.rarity);
  assert.equal(G.CardSystem.catalog.find(c=>c.id===fallback.cardId).rarity, fallback.rarity);
}
const oldWeight = G.CardSystem.CONFIG.rarityRates[0].weight;
G.CardSystem.CONFIG.rarityRates[0].weight = oldWeight - 1;
const preInvalidCoins = G.DB.save.coins;
assert.throws(() => G.CardSystem.open({rng:()=>0}), /deben sumar 100/);
assert.equal(G.DB.save.coins, preInvalidCoins);
G.CardSystem.CONFIG.rarityRates[0].weight = oldWeight;
G.DB.save.coins = 1000; G.DB.save.tickets.t1 = 10;
const result = G.CardSystem.open({rng:()=>0, operationId:'first'});
assert.equal(G.DB.save.coins, 700);
assert.equal(G.DB.save.tickets.t1, 7);
assert.equal(result.after, 1); assert.equal(result.required, 3); assert.equal(result.completed, false); assert.equal(result.unlocked, false);
assert.deepEqual(G.CardSystem.open({rng:()=>0, operationId:'first'}), result);
assert.equal(G.DB.save.coins, 700); assert.equal(G.DB.save.tickets.t1, 7);
const second = G.CardSystem.open({rng:()=>0, operationId:'second'});
assert.equal(second.before, 1); assert.equal(second.after, 2); assert.equal(second.completed, false);
const completed = G.CardSystem.open({rng:()=>0, operationId:'third'});
assert.equal(completed.before, 2); assert.equal(completed.after, 3); assert.equal(completed.completed, true); assert.equal(completed.unlocked, true);
assert.equal(G.DB.save.owned[result.cardId].from, 'card-fragments');
const external = G.CardSystem.catalog.find(c=>c.id!==result.cardId);
G.DB.save.owned[external.id] = {at:Date.now(),from:'other-source'};
const externalCard = G.CardSystem.snapshot().find(c=>c.id===external.id);
assert.equal(externalCard.unlocked, true); assert.equal(externalCard.discovered, false);
G.DB.save.owned[result.cardId] = {at:Date.now(),from:'test'};
G.DB.save.coins = 1000; G.DB.save.tickets.t1 = 10;
const prior = G.DB.save.coins;
const duplicate = G.CardSystem.open({rng:()=>0, operationId:'duplicate'});
assert.equal(duplicate.duplicate, true);
assert.equal(G.DB.save.coins, prior - 300 + G.CardSystem.CONFIG.duplicateCoinsByRarity[duplicate.rarity]);
assert.equal(G.DB.save.tickets.t1, 7);
console.log(`OK: ${G.CardSystem.catalog.length} cartas asociadas; costes, bloqueo por saldo, desbloqueo y duplicado verificados.`);
